import math
import os
import struct
import numpy as np

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cs")

def dbits(d):
    return struct.unpack("<q", struct.pack("<d", d))[0]

def fbits(f):
    return struct.unpack("<i", struct.pack("<f", f))[0]

def dhex(d):
    if math.isnan(d):
        return "nan"
    return "0x%016x" % (dbits(d) & 0xFFFFFFFFFFFFFFFF)

def fhex(f):
    if math.isnan(f):
        return "nan"
    return "0x%08x" % (fbits(f) & 0xFFFFFFFF)

def dlit(d):
    if math.isnan(d):
        return "D(unchecked((long)0x7ff8000000000000))"
    if math.isinf(d):
        return "D(unchecked((long)0x%016x))" % (dbits(d) & 0xFFFFFFFFFFFFFFFF)
    return "D(unchecked((long)0x%016x)) /* %r */" % (dbits(d) & 0xFFFFFFFFFFFFFFFF, d)

def flit(f):
    fv = float(np.float32(f))
    if math.isnan(fv):
        return "F(unchecked((int)0x7fc00000))"
    return "F(unchecked((int)0x%08x)) /* %r */" % (fbits(fv) & 0xFFFFFFFF, fv)

