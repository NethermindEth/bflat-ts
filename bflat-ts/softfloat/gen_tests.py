def gen_checked():
    cases = [
        ("int", -2**31, 2**31 - 1),
        ("uint", 0, 2**32 - 1),
        ("long", -2**63, 2**63 - 1),
        ("ulong", 0, 2**64 - 1),
    ]
    vals = [0.0, 1.5, -1.5, 2147483646.0, 2147483648.0, -2147483649.0,
            4294967296.0, 9.3e18, 1.9e19, -9.3e18, float("nan"),
            float("inf"), float("-inf"), 255.0]
    lines = [HEADER, "    static void Run()\n    {\n        bool ovf;\n"]
    n = 0
    for cty, lo, hi in cases:
        for v in vals:
            if math.isnan(v) or math.isinf(v):
                exp_ovf = True
            else:
                t = math.trunc(v)
                exp_ovf = not (lo - 1 < v < hi + 1)
            lines.append("        ovf = false; try { var r_%d = checked((%s)Id(%s)); if (r_%d.ToString() == \"~\") P(\"\"); } catch (OverflowException) { ovf = true; }\n"
                         % (n, cty, dlit(v), n))
            lines.append("        Ck(\"ck_%s_%d\", ovf.ToString(), \"%s\");\n" % (cty, n, "True" if exp_ovf else "False"))
            n += 1
    lines.append("    }\n")
    lines.append(FOOTER)
    write("checked_conv", lines, n)

def gen_mixed():
    exprs = [
        ("horner", "((2.0 * x + 3.0) * x - 5.0) * x + 7.0", lambda x: ((2.0 * x + 3.0) * x - 5.0) * x + 7.0),
        ("sumsq", "x * x + 0.5 * x", lambda x: x * x + 0.5 * x),
        ("chain_div", "x / 3.0 / 7.0", lambda x: x / 3.0 / 7.0),
        ("mix1", "(x + 0.1) * (x - 0.1)", lambda x: (x + 0.1) * (x - 0.1)),
        ("mix2", "x - x * 0.5 + x / 4.0", lambda x: x - x * 0.5 + x / 4.0),
        ("assoc", "(x + 1e16) - 1e16", lambda x: (x + 1e16) - 1e16),
    ]
    xs = [0.0, 1.0, -1.0, 0.1, 3.5, -2.25, 1e10, -1e10, 12345.6789]
    lines = [HEADER, "    static void Run()\n    {\n        double x;\n"]
    n = 0
    for name, cexpr, fn in exprs:
        for x in xs:
            lines.append("        x = %s;\n" % dlit(x))
            lines.append("        Ck(\"%s_%d\", H(%s), \"%s\");\n" % (name, n, cexpr.replace("x", "Id(x)"), dhex(fn(x))))
            n += 1
    # Kahan summation of 0.1 x 100
    s = 0.0
    c = 0.0
    for _ in range(100):
        y = 0.1 - c
        t = s + y
        c = (t - s) - y
        s = t
    lines.append("""
        double sum = 0.0, comp = 0.0;
        for (int i = 0; i < 100; i++)
        {
            double y = Id(0.1) - comp;
            double t = sum + y;
            comp = (t - sum) - y;
            sum = t;
        }
        Ck("kahan", H(sum), "%s");
""" % dhex(s))
    n += 1
    # NB: not sum() - CPython 3.12+ uses Neumaier compensation there, which
    # is more accurate than the plain accumulation loop the C# side runs.
    plain = 0.0
    for _ in range(100):
        plain += 0.1
    lines.append("""
        double ps = 0.0;
        for (int i = 0; i < 100; i++) ps += Id(0.1);
        Ck("plainsum", H(ps), "%s");
""" % dhex(plain))
    n += 1
    lines.append("    }\n")
    lines.append(FOOTER)
    write("mixed_expr", lines, n)

