    static readonly double[] Coef = { 0.5, -1.25, 3.0, 0.1, -7.0, 2.0 };

    [MethodImpl(NoInl)]
    static double Horner(double x, double[] c)
    {
        double s = 0.0;
        for (int i = 0; i < c.Length; i++) s = s * x + c[i];
        return s;
    }

    [MethodImpl(NoInl)]
    static float DotF(int n)
    {
        float s = 0.0f;
        for (int i = 0; i < n; i++) s += (float)(i + 1) * (1.0f / (float)(i + 3));
        return s;
    }

    [MethodImpl(NoInl)]
    static double Newton(int steps)
    {
        double x = 1.0;
        for (int i = 0; i < steps; i++) x = 0.5 * (x + 2.0 / x);
        return x;
    }

