// float and double arithmetic on a target without the F and D extensions:
// +, -, *, /, % and unary minus.
//
// There are no floating-point instructions, so the compiler turns every
// operation into a call of a soft-float routine (__adddf3, __mulsf3, fmod
// and so on) and keeps the values in integer registers; unary minus becomes
// a flip of the sign bit. The compiler also folds an operation whose
// operands it knows, and treats the calls as the operations they stand for
// when it looks for equal subexpressions and for identities. What can go
// wrong: the wrong routine or the operands in the wrong order, a float
// routine used for a double, a folded result that differs from what the
// routine gives at run time, an identity that does not hold for floating
// point (x + 0 is not x for -0, x * 0 is not 0 for NaN, an infinity or a
// negative x, x - x is not 0 for an infinity, 0 - x is not -x for 0), a
// value lost when an integer register is reused across one of the calls,
// and operands with side effects evaluated out of order.
//
// Tables: each row is two operands and the exact IEEE 754 result as a bit
// pattern. The operands are the special values in every combination (zeros,
// one, infinities, a NaN, the smallest subnormal, the largest finite) and
// cases that round: ties, results that become subnormal, results that
// overflow. Every row is computed at run time through a function pointer.
// A part of the rows is repeated with the operands as constants, so that
// the compiler computes the result itself. A third table has one operand x
// and the results of 24 expressions of x and a constant.
//
// The other checks are longer computations: twelve floating-point and six
// integer values live across the calls, sums in loops, a polynomial, mixed
// float and double, repeated subexpressions, and operands that are calls
// which record the order they ran in.
//
// A result that is a NaN may be any NaN. The expected values were computed
// with exact rational arithmetic, not with these routines. Each failed check
// prints one line; the run ends with ALL PASS or a FAIL count, and the guest
// returns 0 or 1.
