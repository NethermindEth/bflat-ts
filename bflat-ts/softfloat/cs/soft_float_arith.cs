    const MethodImplOptions NoInl = MethodImplOptions.NoInlining;
    const MethodImplOptions Inl = MethodImplOptions.AggressiveInlining;

    static int fails;
    static int checks;

    static bool NanD(ulong b) => (b & 0x7FFFFFFFFFFFFFFFUL) > 0x7FF0000000000000UL;
    static bool NanF(uint b) => (b & 0x7FFFFFFFU) > 0x7F800000U;

    [MethodImpl(NoInl)]
    static void CheckD(string name, ulong expected, double got)
    {
        ulong g = *(ulong*)&got;
        checks++;
        if (NanD(expected) ? NanD(g) : g == expected) return;
        fails++;
        Console.WriteLine("FAIL " + name + " expected 0x" + expected.ToString("x16") + " got 0x" + g.ToString("x16"));
    }

    [MethodImpl(NoInl)]
    static void CheckF(string name, uint expected, float got)
    {
        uint g = *(uint*)&got;
        checks++;
        if (NanF(expected) ? NanF(g) : g == expected) return;
        fails++;
        Console.WriteLine("FAIL " + name + " expected 0x" + expected.ToString("x8") + " got 0x" + g.ToString("x8"));
    }

    [MethodImpl(NoInl)]
    static void CheckI(string name, long expected, long got)
    {
        checks++;
        if (got == expected) return;
        fails++;
        Console.WriteLine("FAIL " + name + " expected " + expected + " got " + got);
    }

    // A constant the compiler can see.
    [MethodImpl(Inl)] static double CD(ulong bits) => BitConverter.UInt64BitsToDouble(bits);
    [MethodImpl(Inl)] static float CF(uint bits) => BitConverter.UInt32BitsToSingle(bits);

    // A value the compiler cannot see.
    [MethodImpl(NoInl)] static double OD(double v) => v;
    [MethodImpl(NoInl)] static float OF(float v) => v;
    [MethodImpl(NoInl)] static long OL(long v) => v;

    [MethodImpl(NoInl)] static double DAdd(double a, double b) => a + b;
    [MethodImpl(NoInl)] static double DSub(double a, double b) => a - b;
    [MethodImpl(NoInl)] static double DMul(double a, double b) => a * b;
    [MethodImpl(NoInl)] static double DDiv(double a, double b) => a / b;
    [MethodImpl(NoInl)] static double DRem(double a, double b) => a % b;
    [MethodImpl(NoInl)] static float FAdd(float a, float b) => a + b;
    [MethodImpl(NoInl)] static float FSub(float a, float b) => a - b;
    [MethodImpl(NoInl)] static float FMul(float a, float b) => a * b;
    [MethodImpl(NoInl)] static float FDiv(float a, float b) => a / b;
    [MethodImpl(NoInl)] static float FRem(float a, float b) => a % b;

    static void RunD(string name, ulong[] t, delegate*<double, double, double> op)
    {
        fixed (ulong* p = t)
        {
            for (int i = 0; i < t.Length; i += 3)
                CheckD(name + " row " + (i / 3), p[i + 2], op(*(double*)(p + i), *(double*)(p + i + 1)));
        }
    }

    static void RunF(string name, uint[] t, delegate*<float, float, float> op)
    {
        fixed (uint* p = t)
        {
            for (int i = 0; i < t.Length; i += 3)
                CheckF(name + " row " + (i / 3), p[i + 2], op(*(float*)(p + i), *(float*)(p + i + 1)));
        }
    }

