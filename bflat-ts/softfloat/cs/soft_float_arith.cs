    static double PressureD(double a0, double a1, double a2, double a3, double a4, double a5, double a6, double a7,
                            double a8, double a9, double a10, double a11,
                            long i0, long i1, long i2, long i3, long i4, long i5)
    {
        double s = a0 * a1 + a2;
        long k = i0 * 31 + i1;
        s = s / a3 - a4 * a5;
        k ^= i2 << 3;
        s = s + (double)k * a6;
        k += i3 * i4;
        double t = a7 * a8 - a9 / a10;
        k -= i5;
        s = s * t + a11 / (double)k;
        double u = a0 + a1 + a2 + a3 + a4 + a5 + a6 + a7 + a8 + a9 + a10 + a11;
        long k2 = i0 + i1 + i2 + i3 + i4 + i5;
        return s + u + (double)(k2 ^ k);
    }

