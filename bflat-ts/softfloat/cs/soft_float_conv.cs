// Conversions to and from float and double on a target without the F and D
// extensions.
//
// Every conversion is a call. float and double to long and ulong use
// runtime routines that return 0 for a NaN and the nearest limit for a
// value out of range. To int and uint there is no routine: the compiler
// converts to long or ulong and then cuts the result down to 32 bits with
// masks. To the types under 32 bits it converts to int first and then
// clamps the int to the range of the type with a compare-and-move sequence
// that needs a scratch register.
// int and uint to floating point are widened to long first and use the long
// routine; float and double convert into each other through __extendsfdf2
// and __truncdfsf2. The checked forms throw instead of saturating. What can
// go wrong: a limit off by one or missing in the 32-bit step, a NaN that
// does not give 0, a negative value to an unsigned type, a uint with its top
// bit set widened as if it were signed, the clamp of a small type that
// overwrites its own operand when the int value is needed again afterwards,
// a result whose upper 32 bits are not
// what its type requires when it is widened afterwards, a long to float
// conversion that goes through double and rounds twice, a tie rounded the
// wrong way, a checked conversion that does not throw or throws for a value
// that fits after truncation, and a constant operand converted by the
// compiler to something else than the routine returns.
//
// Tables: each row is an operand and the exact results as bit patterns.
// float and double to int, uint, long, ulong and to the four small types;
// the same operands checked, with a flag for the rows that must throw;
// int, uint, long, ulong to float and double with operands on both sides of
// every rounding limit; double to float and float to double. Every row is
// converted at run time; a part is repeated with constant operands. A result
// that is a NaN may be any NaN.
//
// The expected values were computed with exact rational arithmetic. Each
// failed check prints one line; the run ends with ALL PASS or a FAIL count,
// and the guest returns 0 or 1.
using System;
using System.Runtime.CompilerServices;

unsafe class Program
{
    const MethodImplOptions NoInl = MethodImplOptions.NoInlining;
    const MethodImplOptions Inl = MethodImplOptions.AggressiveInlining;

    static int fails;
    static int checks;

    static bool NanD(ulong b) => (b & 0x7FFFFFFFFFFFFFFFUL) > 0x7FF0000000000000UL;
    static bool NanF(uint b) => (b & 0x7FFFFFFFU) > 0x7F800000U;

    [MethodImpl(NoInl)]
    static void CheckD(string name, ulong expected, double got)
    {
        ulong g = *(ulong*)&got;
        checks++;
        if (NanD(expected) ? NanD(g) : g == expected) return;
        fails++;
        Console.WriteLine("FAIL " + name + " expected 0x" + expected.ToString("x16") + " got 0x" + g.ToString("x16"));
    }

    [MethodImpl(NoInl)]
    static void CheckF(string name, uint expected, float got)
    {
        uint g = *(uint*)&got;
        checks++;
        if (NanF(expected) ? NanF(g) : g == expected) return;
        fails++;
        Console.WriteLine("FAIL " + name + " expected 0x" + expected.ToString("x8") + " got 0x" + g.ToString("x8"));
    }

    [MethodImpl(NoInl)]
    static void CheckL(string name, long expected, long got)
    {
        checks++;
        if (got == expected) return;
        fails++;
        Console.WriteLine("FAIL " + name + " expected 0x" + expected.ToString("x16") + " got 0x" + got.ToString("x16"));
    }

    // Constants the compiler can see.
    [MethodImpl(Inl)] static double CD(ulong bits) => BitConverter.UInt64BitsToDouble(bits);
    [MethodImpl(Inl)] static float CF(uint bits) => BitConverter.UInt32BitsToSingle(bits);
    [MethodImpl(Inl)] static long CL(long v) => v;
    [MethodImpl(Inl)] static ulong CU(ulong v) => v;
    [MethodImpl(Inl)] static uint CU32(uint v) => v;

    // ---- floating point to integer; the result is widened in the method ----

    [MethodImpl(NoInl)] static long D2I32(double x) => (int)x;
    [MethodImpl(NoInl)] static long D2U32(double x) => (uint)x;
    [MethodImpl(NoInl)] static long D2I64(double x) => (long)x;
    [MethodImpl(NoInl)] static ulong D2U64(double x) => (ulong)x;
    [MethodImpl(NoInl)] static long F2I32(float x) => (int)x;
    [MethodImpl(NoInl)] static long F2U32(float x) => (uint)x;
    [MethodImpl(NoInl)] static long F2I64(float x) => (long)x;
    [MethodImpl(NoInl)] static ulong F2U64(float x) => (ulong)x;

    // The result is returned as it is and widened by the caller.
    [MethodImpl(NoInl)] static int D2I32R(double x) => (int)x;
    [MethodImpl(NoInl)] static uint D2U32R(double x) => (uint)x;
    [MethodImpl(NoInl)] static int F2I32R(float x) => (int)x;
    [MethodImpl(NoInl)] static uint F2U32R(float x) => (uint)x;

    [MethodImpl(NoInl)] static long D2I8(double x) => (sbyte)x;
    [MethodImpl(NoInl)] static long D2U8(double x) => (byte)x;
    [MethodImpl(NoInl)] static long D2I16(double x) => (short)x;
    [MethodImpl(NoInl)] static long D2U16(double x) => (ushort)x;
    [MethodImpl(NoInl)] static long F2I8(float x) => (sbyte)x;
    [MethodImpl(NoInl)] static long F2U8(float x) => (byte)x;
    [MethodImpl(NoInl)] static long F2I16(float x) => (short)x;
    [MethodImpl(NoInl)] static long F2U16(float x) => (ushort)x;

    // The converted value used at once: as an index, in arithmetic, compared.
    [MethodImpl(NoInl)]
    static long UsedD(double x, long* tab)
    {
        long h = tab[(byte)x];
        h = h * 31 + tab[(uint)x & 0xFF];
        h = h * 31 + ((int)x >> 3);
        h = h * 31 + (long)((uint)x >> 3);
        h = h * 31 + ((int)x < 0 ? 1 : 2) + ((uint)x > 0x7FFFFFFFu ? 4 : 8);
        h = h * 31 + (int)x * 3L + (uint)x * 5L;
        return h;
    }

    [MethodImpl(NoInl)]
    static long UsedRef(long i32, long u32, long u8, long* tab)
    {
        long h = tab[u8];
        h = h * 31 + tab[u32 & 0xFF];
        h = h * 31 + (i32 >> 3);
        h = h * 31 + (u32 >> 3);
        h = h * 31 + (i32 < 0 ? 1 : 2) + (u32 > 0x7FFFFFFFL ? 4 : 8);
        h = h * 31 + i32 * 3L + u32 * 5L;
        return h;
    }

    // A small type and int from the same operand: the int conversion is done
    // once and its result is still needed after it has been clamped.
    [MethodImpl(NoInl)]
    static long U8AndI32(double x) { int b = (byte)x; int i = (int)x; return ((long)b << 32) | (uint)i; }

    [MethodImpl(NoInl)]
    static long I8AndI32(double x) { int b = (sbyte)x; int i = (int)x; return ((long)b << 32) | (uint)i; }

    [MethodImpl(NoInl)]
    static long U16AndI32(double x) { int b = (ushort)x; int i = (int)x; return ((long)b << 32) | (uint)i; }

    [MethodImpl(NoInl)]
    static long I16AndI32(double x) { int b = (short)x; int i = (int)x; return ((long)b << 32) | (uint)i; }

    [MethodImpl(NoInl)]
    static long U8AndI32F(float x) { int b = (byte)x; int i = (int)x; return ((long)b << 32) | (uint)i; }

    [MethodImpl(NoInl)]
    static long I16AndI32F(float x) { int b = (short)x; int i = (int)x; return ((long)b << 32) | (uint)i; }

    // ---- checked ----

    [MethodImpl(NoInl)]
    static long CkD(double x, int t)
    {
        switch (t)
        {
            case 0: return checked((sbyte)x);
            case 1: return checked((byte)x);
            case 2: return checked((short)x);
            case 3: return checked((ushort)x);
            case 4: return checked((int)x);
            case 5: return checked((uint)x);
            case 6: return checked((long)x);
            default: return unchecked((long)checked((ulong)x));
        }
    }

    [MethodImpl(NoInl)]
    static long CkF(float x, int t)
    {
        switch (t)
        {
            case 0: return checked((sbyte)x);
            case 1: return checked((byte)x);
            case 2: return checked((short)x);
            case 3: return checked((ushort)x);
            case 4: return checked((int)x);
            case 5: return checked((uint)x);
            case 6: return checked((long)x);
            default: return unchecked((long)checked((ulong)x));
        }
    }

    [MethodImpl(NoInl)]
    static bool TryD(double x, int t, out long r)
    {
        try { r = CkD(x, t); return true; }
        catch (OverflowException) { r = 0; return false; }
    }

    [MethodImpl(NoInl)]
    static bool TryF(float x, int t, out long r)
    {
        try { r = CkF(x, t); return true; }
        catch (OverflowException) { r = 0; return false; }
    }

    // ---- integer to floating point ----

    [MethodImpl(NoInl)] static float I32ToF(int v) => v;
    [MethodImpl(NoInl)] static double I32ToD(int v) => v;
    [MethodImpl(NoInl)] static float U32ToF(uint v) => v;
    [MethodImpl(NoInl)] static double U32ToD(uint v) => v;
    [MethodImpl(NoInl)] static float I64ToF(long v) => v;
    [MethodImpl(NoInl)] static double I64ToD(long v) => v;
    [MethodImpl(NoInl)] static float U64ToF(ulong v) => v;
    [MethodImpl(NoInl)] static double U64ToD(ulong v) => v;
    [MethodImpl(NoInl)] static float I8ToF(sbyte v) => v;
    [MethodImpl(NoInl)] static double U8ToD(byte v) => v;
    [MethodImpl(NoInl)] static double I16ToD(short v) => v;
    [MethodImpl(NoInl)] static float U16ToF(ushort v) => v;
    [MethodImpl(NoInl)] static double CharToD(char v) => v;

    // A uint that is the low half of a long: its register may hold anything above bit 31.
    [MethodImpl(NoInl)] static double LowHalfToD(long v) => (uint)v;
    [MethodImpl(NoInl)] static float LowHalfToF(long v) => (uint)v;
    [MethodImpl(NoInl)] static double LowHalfSignedToD(long v) => (int)v;

    // ---- float and double ----

    [MethodImpl(NoInl)] static float D2F(double x) => (float)x;
    [MethodImpl(NoInl)] static double F2D(float x) => x;

