    static void RunToInt()
    {
        long* tab = stackalloc long[256];
        for (int i = 0; i < 256; i++) tab[i] = (i + 1) * 0x0101010101010101L + i;

        fixed (ulong* p = TabD2I)
        fixed (ulong* q = TabD2Small)
        {
            for (int i = 0; i < TabD2I.Length; i += 5)
            {
                double x = *(double*)(p + i);
                string r = "double row " + (i / 5);
                CheckL(r + " to int", (long)p[i + 1], D2I32(x));
                CheckL(r + " to uint", (long)p[i + 2], D2U32(x));
                CheckL(r + " to long", (long)p[i + 3], D2I64(x));
                CheckL(r + " to ulong", (long)p[i + 4], (long)D2U64(x));
                CheckL(r + " to int, widened by the caller", (long)p[i + 1], D2I32R(x));
                CheckL(r + " to uint, widened by the caller", (long)p[i + 2], D2U32R(x));
                CheckL(r + " to sbyte", (long)q[i + 1], D2I8(x));
                CheckL(r + " to byte", (long)q[i + 2], D2U8(x));
                CheckL(r + " to short", (long)q[i + 3], D2I16(x));
                CheckL(r + " to ushort", (long)q[i + 4], D2U16(x));
                CheckL(r + " converted and used", UsedRef((long)p[i + 1], (long)p[i + 2], (long)q[i + 2], tab),
                       UsedD(x, tab));
                long lo = (long)(uint)p[i + 1];
                CheckL(r + " to byte and then to int", ((long)q[i + 2] << 32) | lo, U8AndI32(x));
                CheckL(r + " to sbyte and then to int", ((long)q[i + 1] << 32) | lo, I8AndI32(x));
                CheckL(r + " to ushort and then to int", ((long)q[i + 4] << 32) | lo, U16AndI32(x));
                CheckL(r + " to short and then to int", ((long)q[i + 3] << 32) | lo, I16AndI32(x));
            }
        }
        fixed (ulong* p = TabF2I)
        fixed (ulong* q = TabF2Small)
        {
            for (int i = 0; i < TabF2I.Length; i += 5)
            {
                float x = *(float*)(p + i);
                string r = "float row " + (i / 5);
                CheckL(r + " to int", (long)p[i + 1], F2I32(x));
                CheckL(r + " to uint", (long)p[i + 2], F2U32(x));
                CheckL(r + " to long", (long)p[i + 3], F2I64(x));
                CheckL(r + " to ulong", (long)p[i + 4], (long)F2U64(x));
                CheckL(r + " to int, widened by the caller", (long)p[i + 1], F2I32R(x));
                CheckL(r + " to uint, widened by the caller", (long)p[i + 2], F2U32R(x));
                CheckL(r + " to sbyte", (long)q[i + 1], F2I8(x));
                CheckL(r + " to byte", (long)q[i + 2], F2U8(x));
                CheckL(r + " to short", (long)q[i + 3], F2I16(x));
                CheckL(r + " to ushort", (long)q[i + 4], F2U16(x));
                long lo = (long)(uint)p[i + 1];
                CheckL(r + " to byte and then to int", ((long)q[i + 2] << 32) | lo, U8AndI32F(x));
                CheckL(r + " to short and then to int", ((long)q[i + 3] << 32) | lo, I16AndI32F(x));
            }
        }
    }

    static readonly string[] CkNames = { "sbyte", "byte", "short", "ushort", "int", "uint", "long", "ulong" };

    static void RunChecked()
    {
        fixed (ulong* p = TabCkD)
        {
            for (int i = 0; i < TabCkD.Length; i += 9)
            {
                for (int t = 0; t < 8; t++)
                {
                    bool ok = TryD(*(double*)(p + i), t, out long r);
                    string n = "double row " + (i / 9) + " checked to " + CkNames[t];
                    CheckL(n + ", does not throw", TabCkDOk[i / 9 * 8 + t], ok ? 1 : 0);
                    CheckL(n, (long)p[i + 1 + t], r);
                }
            }
        }
