        }
    }

    static void RunFromInt()
    {
        for (int i = 0; i < TabI32.Length; i += 3)
        {
            long v = (long)TabI32[i];
            uint f = (uint)TabI32[i + 1];
            ulong d = TabI32[i + 2];
            string r = "int row " + (i / 3);
            CheckF(r + " to float", f, I32ToF((int)v));
            CheckD(r + " to double", d, I32ToD((int)v));
            CheckD(r + " as the low half of a long to double", d, LowHalfSignedToD(v ^ 0x5A5A5A5A00000000L));
            if (v == (sbyte)v) CheckF(r + " as sbyte to float", f, I8ToF((sbyte)v));
            if (v == (byte)v) CheckD(r + " as byte to double", d, U8ToD((byte)v));
            if (v == (short)v) CheckD(r + " as short to double", d, I16ToD((short)v));
            if (v == (ushort)v) CheckF(r + " as ushort to float", f, U16ToF((ushort)v));
            if (v == (char)v) CheckD(r + " as char to double", d, CharToD((char)v));
        }
        for (int i = 0; i < TabU32.Length; i += 3)
        {
            uint v = (uint)TabU32[i];
            string r = "uint row " + (i / 3);
            CheckF(r + " to float", (uint)TabU32[i + 1], U32ToF(v));
            CheckD(r + " to double", TabU32[i + 2], U32ToD(v));
            CheckD(r + " as the low half of a long to double", TabU32[i + 2], LowHalfToD((long)v | 0x7BCDEF0100000000L));
            CheckF(r + " as the low half of a long to float", (uint)TabU32[i + 1],
                   LowHalfToF((long)v | unchecked((long)0xFFFFFFFF00000000UL)));
        }
        for (int i = 0; i < TabI64.Length; i += 3)
        {
            string r = "long row " + (i / 3);
            CheckF(r + " to float", (uint)TabI64[i + 1], I64ToF((long)TabI64[i]));
            CheckD(r + " to double", TabI64[i + 2], I64ToD((long)TabI64[i]));
        }
        for (int i = 0; i < TabU64.Length; i += 3)
        {
            string r = "ulong row " + (i / 3);
            CheckF(r + " to float", (uint)TabU64[i + 1], U64ToF(TabU64[i]));
            CheckD(r + " to double", TabU64[i + 2], U64ToD(TabU64[i]));
        }
    }

