    [MethodImpl(NoInl)] static long SMax(float a, float b) => BitConverter.SingleToInt32Bits(MathF.Max(a, b));
    [MethodImpl(NoInl)] static long SMin(float a, float b) => BitConverter.SingleToInt32Bits(MathF.Min(a, b));

    [MethodImpl(NoInl)]
    static int ClassF(float x)
        => B(float.IsNaN(x)) | B(float.IsInfinity(x)) << 1 | B(float.IsFinite(x)) << 2 | B(float.IsNegative(x)) << 3
           | B(float.IsNormal(x)) << 4 | B(float.IsSubnormal(x)) << 5 | B(float.IsPositiveInfinity(x)) << 6
           | B(float.IsNegativeInfinity(x)) << 7 | B(float.IsPositive(x)) << 8;

    [MethodImpl(NoOpt)]
    static int ClassRef(uint b)
    {
        uint mag = b & 0x7FFFFFFF;
        bool neg = (b >> 31) != 0;
        int m = 0;
        if (mag > 0x7F800000) m |= 1;
        if (mag == 0x7F800000) m |= 2;
        if (mag < 0x7F800000) m |= 4;
        if (neg) m |= 8;
        if (mag < 0x7F800000 && mag >= 0x00800000) m |= 16;
        if (mag < 0x00800000 && mag != 0) m |= 32;
        if (b == 0x7F800000) m |= 64;
        if (b == 0xFF800000) m |= 128;
        if (!neg) m |= 256;
        return m;
    }

