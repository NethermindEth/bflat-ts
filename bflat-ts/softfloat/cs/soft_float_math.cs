// Math functions and bit-level access for float and double on a target
// without the F and D extensions.
//
// With floating-point instructions Sqrt, Abs, Min, Max, Floor, Ceiling,
// Round, Truncate, FusedMultiplyAdd and CopySign are single instructions,
// and the compiler replaces the calls with them. Here it must not: each one
// stays a call of the library implementation, which does the work with the
// soft-float routines or on the bits. BitConverter and unary minus work on
// the integer register that holds the value. What can go wrong: one of the
// replacements still made (the build then has an instruction the target
// lacks, or the wrong result), a library implementation that gives another
// result than the instruction it stands for (the sign of a zero, a NaN
// operand of Min and Max, a tie in Round, a product that is not fused), and,
// for float, the upper half of the register: a routine returns a float with
// anything above bit 31, and the bits of that float taken as an int have to
// be sign-extended before they are used as a long, compared or tested for
// sign.
//
// Tables: an operand and the exact results of Sqrt, Abs, Floor, Ceiling,
// Truncate, Round to even, Round away from zero and negation; pairs with
// Min, Max and CopySign; triples with FusedMultiplyAdd, among them products
// whose low bits only a fused operation keeps. Then the bits of the result
// of every arithmetic routine and conversion widened to 64 bits both ways;
// IsNaN and its relatives on a float whose register is dirty above bit 31
// (raw calls through a function pointer that passes a long, only where
// registers are 64 bits wide); BitConverter
// round trips, signalling NaNs included; a few more Math functions; and
// formatting and parsing, which run a lot of library floating-point code.
// A result that is a NaN may be any NaN.
//
// Sin, Cos, Exp, Log, Pow and the like are replaced by empty stubs in this
// build and are not tested. The expected values were computed with exact
// rational arithmetic. Each failed check prints one line; the run ends with
// ALL PASS or a FAIL count, and the guest returns 0 or 1.
