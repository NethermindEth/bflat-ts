    // The bits of a float as a long: equal to the expected bits sign-extended;
    // for a NaN, whose bits are free, at least sign-extended.
    static void BitsS(string name, uint expected, long got)
        => CheckL(name + " bits widened signed", NanF(expected) ? (long)(int)got : (long)(int)expected, got);

    static void BitsU(string name, uint expected, ulong got)
        => CheckL(name + " bits widened unsigned", NanF(expected) ? (long)(uint)got : (long)expected, (long)got);

    static void RunBits()
    {
        fixed (uint* p = TabOpBitsF)
        {
            for (int i = 0; i < TabOpBitsF.Length; i += 7)
            {
                float a = *(float*)(p + i), b = *(float*)(p + i + 1);
                string r = "float pair " + (i / 7) + " ";
                BitsS(r + "sum", p[i + 2], SAdd(a, b));
                BitsU(r + "sum", p[i + 2], UAdd(a, b));
                BitsS(r + "difference", p[i + 3], SSub(a, b));
                BitsU(r + "difference", p[i + 3], USub(a, b));
                BitsS(r + "product", p[i + 4], SMul(a, b));
                BitsU(r + "product", p[i + 4], UMul(a, b));
                BitsS(r + "quotient", p[i + 5], SDiv(a, b));
                BitsU(r + "quotient", p[i + 5], UDiv(a, b));
                BitsS(r + "remainder", p[i + 6], SRem(a, b));
                BitsU(r + "remainder", p[i + 6], URem(a, b));
                if (!NanF(p[i + 2])) CheckL(r + "sign of the sum", (long)(p[i + 2] >> 31), B(NegAdd(a, b)));
                if (!NanF(p[i + 4])) CheckL(r + "sign of the product", (long)(p[i + 4] >> 31), B(NegMul(a, b)));
            }
        }
        for (int i = 0; i < TabD2FBits.Length; i += 2)
        {
            BitsS("double " + (i / 2) + " to float", (uint)TabD2FBits[i + 1], SD2F(D(TabD2FBits[i])));
            BitsU("double " + (i / 2) + " to float", (uint)TabD2FBits[i + 1], UD2F(D(TabD2FBits[i])));
        }
        for (int i = 0; i < TabL2FBits.Length; i += 2)
        {
            BitsS("long " + (i / 2) + " to float", (uint)TabL2FBits[i + 1], SL2F((long)TabL2FBits[i]));
            BitsU("long " + (i / 2) + " to float", (uint)TabL2FBits[i + 1], UL2F((long)TabL2FBits[i]));
        }
        fixed (uint* p = TabUnaryF)
        {
            for (int i = 0; i < TabUnaryF.Length; i += 9)
                BitsS("float row " + (i / 9) + " Sqrt", p[i + 1], SSqrt(*(float*)(p + i)));
        }
    }

    static void RunDirty()
    {
        for (int n = 0; n < BitsF.Length; n++)
        {
            uint b = BitsF[n];
            uint c = BitsF[(n + 5) % BitsF.Length];
            string r = "float " + n + " in a dirty register, ";
            for (int pass = 0; pass < 2; pass++)
            {
                ulong v = b | (pass == 0 ? Junk : Ones);
                ulong w = c | (pass == 0 ? Ones : Junk);
                CheckL(r + "negated, signed", (long)(int)(b ^ 0x80000000U), ((delegate*<ulong, long>)(delegate*<float, long>)&SNeg)(v));
                CheckL(r + "negated, unsigned", (long)(b ^ 0x80000000U), (long)((delegate*<ulong, ulong>)(delegate*<float, ulong>)&UNeg)(v));
                CheckL(r + "Abs", (long)(b & 0x7FFFFFFFU), ((delegate*<ulong, long>)(delegate*<float, long>)&SAbs)(v));
                CheckL(r + "CopySign", (long)(int)((b & 0x7FFFFFFFU) | (c & 0x80000000U)),
                       ((delegate*<ulong, ulong, long>)(delegate*<float, float, long>)&SCopySign)(v, w));
                CheckL(r + "classification", ClassRef(b), ((delegate*<ulong, int>)(delegate*<float, int>)&ClassF)(v));
                // Min and Max of a value with itself are the value.
                if (!NanF(b))
                {
                    CheckL(r + "Max with itself", (long)(int)b, ((delegate*<ulong, ulong, long>)(delegate*<float, float, long>)&SMax)(v, b));
                    CheckL(r + "Min with itself", (long)(int)b, ((delegate*<ulong, ulong, long>)(delegate*<float, float, long>)&SMin)(v, b));
                }
            }
            CheckL(r + "classification, typed", ClassRef(b), ClassF(F(b)));
        }
    }

    static void RunBitConverter()
    {
        for (int n = 0; n < BitsD.Length; n++)
        {
            ulong b = BitsD[n];
            string r = "double bits " + n + " ";
            CheckL(r + "through Int64BitsToDouble", (long)b, D2L(L2D((long)b)));
            CheckL(r + "through UInt64BitsToDouble", (long)b, (long)D2UL(UL2D(b)));
            CheckL(r + "read from memory", (long)b, D2L(D(b)));
            double d = L2D((long)b);
            CheckL(r + "written to memory", (long)b, *(long*)&d);
            byte[] bytes = BytesD(d);
            ulong back = 0;
            for (int k = 7; k >= 0; k--) back = (back << 8) | bytes[k];
            CheckL(r + "as bytes", (long)b, (long)back);
            CheckL(r + "from bytes", (long)b, D2L(FromBytesD(bytes)));
        }
        for (int n = 0; n < BitsF.Length; n++)
        {
            uint b = BitsF[n];
            string r = "float bits " + n + " ";
            CheckL(r + "through Int32BitsToSingle", (int)b, F2I(I2F((int)b)));
            CheckL(r + "through UInt32BitsToSingle", b, F2U(U2F(b)));
            CheckL(r + "read from memory", (int)b, F2I(F(b)));
            float f = U2F(b);
            CheckL(r + "written to memory", b, *(uint*)&f);
            byte[] bytes = BytesF(f);
            uint back = 0;
            for (int k = 3; k >= 0; k--) back = (back << 8) | bytes[k];
            CheckL(r + "as bytes", b, back);
            CheckL(r + "from bytes", (int)b, F2I(FromBytesF(bytes)));
        }
    }

    [MethodImpl(NoInl)]
    static int SignOrThrow(double x)
    {
        try { return Math.Sign(x); }
        catch (ArithmeticException) { return 99; }
    }

